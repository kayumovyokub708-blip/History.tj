export function normalize(s: string) {
  return s.toLowerCase().replace(/[ё]/g, "е").trim()
}

export function searchFAQ(query: string): FAQ[] {
  const q = normalize(query)
  if (!q || q.length < 2) return []
  const words = q.split(/\s+/).filter(Boolean)
  return FAQ_LIST
    .map((item) => {
      const hay = normalize([item.q, item.a, ...item.keywords].join(" "))
      let score = 0
      for (const w of words) {
        if (hay.includes(w)) score += 2
        if (item.keywords.some((k) => normalize(k).includes(w) || w.includes(normalize(k)))) score += 3
      }
      if (normalize(item.q).includes(q)) score += 5
      return { item, score }
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5)
    .map((x) => x.item)
}
